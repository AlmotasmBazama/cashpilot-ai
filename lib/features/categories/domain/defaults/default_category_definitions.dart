class DefaultCategoryDefinition {
  const DefaultCategoryDefinition({
    required this.id,
    required this.name,
    required this.type,
    required this.iconKey,
    required this.colorArgb,
    required this.localizationKey,
    required this.sortOrder,
  });

  final String id;
  final String name;
  final CategoryType type;
  final String iconKey;
  final int colorArgb;
  final String localizationKey;
  final int sortOrder;

  Category toCategory({DateTime? timestamp}) {
    final now = timestamp ?? DateTime.now().toUtc();

    return Category(
      id: id,
      name: name,
      type: type,
      icon: CategoryIcon(key: iconKey),
      color: CategoryColor(argb: colorArgb),
      parentCategoryId: null,
      isDefault: true,
      isArchived: false,
      sortOrder: sortOrder,
      createdAt: now,
      updatedAt: now,
    );
  }
}

List<Category> buildDefaultCategories({DateTime? timestamp}) {
  return defaultCategoryDefinitions
      .map((definition) => definition.toCategory(timestamp: timestamp))
      .toList(growable: false);
}

